CREATE DATABASE IF NOT EXISTS INFORMATIONAL_SYSTEM_OF_MEDICAL_CENTRE CHARACTER SET utf8mb4;

USE INFORMATIONAL_SYSTEM_OF_MEDICAL_CENTRE;

CREATE TABLE IF NOT EXISTS Specialities(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    SpecialityName VARCHAR(25) NOT NULL
);

CREATE TABLE IF NOT EXISTS Roles(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    RoleName VARCHAR(25) NOT NULL
);

CREATE TABLE IF NOT EXISTS Services(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    ServiceName VARCHAR(25) NOT NULL
);

CREATE TABLE IF NOT EXISTS PatientTypes(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    PatientTypeName VARCHAR(25) NOT NULL
);

CREATE TABLE IF NOT EXISTS Diagnoses(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    DiagnosisName VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS Consumables(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    ConsumableName VARCHAR(25) NOT NULL,
    Cost DECIMAL(10,2) NOT NULL,
    CONSTRAINT C_POSITIVE_COST CHECK(Cost > 0)
);

CREATE TABLE IF NOT EXISTS TreatmentTypes(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    TreatmentTypeName VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS Counterparties(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    CounterpartiesName VARCHAR(100) NOT NULL,
    PhoneNumber VARCHAR(13)
);

CREATE TABLE IF NOT EXISTS Warehouses(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    WarehousesName VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS Analyses(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    CounterpartyId INT NULL,
    AnalysisName VARCHAR(100) NOT NULL,
    
    CONSTRAINT FK_COUNTREPARTIES_ANALYSES FOREIGN KEY(CounterpartyId) REFERENCES Counterparties(Id)
    ON DELETE NO ACTION
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS Contracts(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    ContractName VARCHAR(50) NOT NULL,
    DateOfStart DATE NOT NULL,
    DateOfEnd DATE NOT NULL,
	CounterpartyId INT NOT NULL,
    PaymentType ENUM('Оплата', 'Дохід'),
    Price DECIMAL(12, 2) NOT NULL,
    
    CONSTRAINT C_CONTRACT_POSITIVE_PRICE CHECK(Price > 0),
    
    CONSTRAINT C_DATESTART_DATEEND CHECK(DateOfStart < DateOfEnd),
    
    CONSTRAINT FK_COUNTREPARTIES_CONTRACTS FOREIGN KEY(CounterpartyId) REFERENCES Counterparties(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS Workers(
	id INT PRIMARY KEY AUTO_INCREMENT,
    FirstName VARCHAR(50) NOT NULL,
    LastName VARCHAR(50) NOT NULL,
    MiddleName VARCHAR(50) NOT NULL,
    SpecialityId INT NULL,
    PhoneNumber VARCHAR(13) NOT NULL,
    Email VARCHAR(50) NOT NULL,
    BirthDate DATE NOT NULL,
    WorkerPasswordHash CHAR(60) NOT NULL,
    IsBlocked BOOLEAN NOT NULL DEFAULT FALSE,
	WorkerLogin VARCHAR(50)  NOT NULL,
	WorkerRoleId INT NOT NULL,
    Gender ENUM("Чоловік", "Жінка") NOT NULL,
    
    CONSTRAINT UQ_WORKER_LOGIN UNIQUE(WorkerLogin),
    
    CONSTRAINT UQ_WORKER_EMAIL UNIQUE(Email),
    
    CONSTRAINT FK_ROLE_WORKER FOREIGN KEY(WorkerRoleId) REFERENCES Roles(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
    CONSTRAINT FK_SPECIALITY_WORKER FOREIGN KEY(SpecialityId) REFERENCES Specialities(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS WorkerServices(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    WorkerId INT NOT NULL,
    ServiceId INT NOT NULL,
    Price DECIMAL(7, 2) NOT NULL,
    IsActive BOOLEAN DEFAULT(TRUE),
    
    CONSTRAINT FK_WORKER_WORKERSERVICES FOREIGN KEY(WorkerId) REFERENCES Workers(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
    CONSTRAINT FK_SERVICES_WORKERSERVICES FOREIGN KEY(ServiceId) REFERENCES Services(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS Patients(
	id INT PRIMARY KEY AUTO_INCREMENT,
    FirstName VARCHAR(50) NOT NULL,
    LastName VARCHAR(50) NOT NULL,
    MiddleName VARCHAR(50) NOT NULL,
    PhoneNumber VARCHAR(13) NOT NULL,
    BirthDate DATE NOT NULL,
    IsBlocked BOOLEAN NOT NULL DEFAULT FALSE,
    Gender ENUM("Чоловік", "Жінка") NOT NULL,
    PatientTypeId INT NOT NULL,
    FamilyDoctorId INT NULL,
    
    CONSTRAINT FK_PATIENTTYPE_WORKER FOREIGN KEY(PatientTypeId) REFERENCES PatientTypes(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
    CONSTRAINT FK_WORKER_PATIENT FOREIGN KEY(FamilyDoctorId) REFERENCES Workers(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS WorkerSchedule(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    WorkerId INT NOT NULL,
    StartTime TIME NOT NULL,
    EndTime TIME NOT NULL, 
    WorkerSchedule DATE NOT NULL,
    
    CONSTRAINT C_STARTTIME_ENDTIME CHECK(StartTime < EndTime),
    
    CONSTRAINT FK_WORKER_Schedule FOREIGN KEY(WorkerId) REFERENCES Workers(Id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS Appointments(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    WorkerId INT NOT NULL,
    PatientId INT NOT NULL,
    AppointmentDateTime DATETIME NOT NULL,
    AppointmentStatus ENUM('Заплановано', 'Відмінено', 'Закінчено', 'Не з\'явився') NOT NULL DEFAULT('Заплановано'),
    Duration INT NOT NULL,
    
    CONSTRAINT C_POSITIVE_DURATION CHECK(Duration > 0),
    
    CONSTRAINT FK_WORKER_APPOINTMENT FOREIGN KEY(WorkerId) REFERENCES Workers(Id)
    ON DELETE NO ACTION
    ON UPDATE CASCADE,
    
    CONSTRAINT FK_PATIENT_APPOINTMENT FOREIGN KEY(PatientId) REFERENCES Patients(Id)
);

CREATE TABLE IF NOT EXISTS AppointmentsServices(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    AppointmentId INT NOT NULL,
    WorkerServiceId INT NOT NULL,
    Price DECIMAL(10,2) NOT NULL,
    
    CONSTRAINT C_POSITIVE_PRICE CHECK(Price > 0),
    
    CONSTRAINT FK_APPOINTMENTS_APPOINTMENTSSERVICES FOREIGN KEY(AppointmentId) REFERENCES Appointments(Id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,
    
    CONSTRAINT FK_WORKERSERVICES_APPOINTMENTSSERVICES FOREIGN KEY(WorkerServiceId) REFERENCES WorkerServices(Id)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);

CREATE TABLE IF NOT EXISTS Transactions(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    TransactionType ENUM('Дохід', 'Витрата') NOT NULL,
    AmountOfMoney DECIMAL(12, 2) NOT NULL,
    TransactionDate DATE NOT NULL,
	AppointmentId INT NULL,
    ContractId INT NULL,
    
    CONSTRAINT C_TRANSACTION_POSITIVE_AMOUNTOFMONEY CHECK(AmountOfMoney > 0),
    
    CONSTRAINT FK_APPOINTMENTS_TRANSACTIONS FOREIGN KEY(AppointmentId) REFERENCES Appointments(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
    CONSTRAINT FK_CONTRACTS_TRANSACTIONS FOREIGN KEY(ContractId) REFERENCES Contracts(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS MedicalRecords(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    MedicalRecordDate DATE NOT NULL,
	AppointmentId INT NOT NULL,
    
    CONSTRAINT FK_APPOINTMENTS_MEDICALRECORDS FOREIGN KEY(AppointmentId) REFERENCES Appointments(Id)
    ON DELETE NO ACTION
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS MedicalVacations(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    MedicalRecordId INT NOT NULL,
    DateOfEnd DATE NOT NULL,
    DateOfStart DATE NOT NULL,
    
    CONSTRAINT UQ_MEDICALVACATIONS_MEDICALRECORD UNIQUE(MedicalRecordId),
    
	CONSTRAINT FK_MEDICALRECORDS_MEDICALVACATIONS FOREIGN KEY(MedicalRecordId) REFERENCES MedicalRecords(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS MedicalRecordsAnalyses(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    MedicalRecordId INT NOT NULL,
    AnalysisId INT NOT NULL,
    Result VARCHAR(30),
    
    CONSTRAINT FK_ANALYSES_MEDICALRECORDSANALYSES FOREIGN KEY(AnalysisId) REFERENCES Analyses(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
	CONSTRAINT FK_MEDICALRECORDS_MEDICALRECORDSANALYSES FOREIGN KEY(MedicalRecordId) REFERENCES MedicalRecords(Id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS MedicalRecordsDiagnoses(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    MedicalRecordId INT NOT NULL,
    DiagnosisId INT NOT NULL,
    
    CONSTRAINT FK_DIAGNOSES_MEDICALRECORDSDIAGNOSES FOREIGN KEY(DiagnosisId) REFERENCES Diagnoses(Id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,
    
	CONSTRAINT FK_MEDICALRECORDS_MEDICALRECORDSDIAGNOSES FOREIGN KEY(MedicalRecordId) REFERENCES MedicalRecords(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS MedicalRecordsTreatments(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    MedicalRecordId INT NOT NULL,
    TreatmentId INT NOT NULL,
    TreatmentDescription VARCHAR(30),
    
    CONSTRAINT FK_TREATMENTS_MEDICALRECORDSTREATMENTS FOREIGN KEY(TreatmentId) REFERENCES TreatmentTypes(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
	CONSTRAINT FK_MEDICALRECORDS_MEDICALRECORDSTREATMENTS FOREIGN KEY(MedicalRecordId) REFERENCES MedicalRecords(Id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS WarehouseStock(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    StockStatus ENUM('В наявності', 'В дорозі', 'Закінчилась') NOT NULL,
    SpecialConditions VARCHAR(50),
    ExpirationDate DATE NOT NULL,
    InitialAmount INT NOT NULL,
    RemainingAmount INT NOT NULL DEFAULT(InitialAmount),
	ConsumableId INT NOT NULL,
    WarehouseId INT NOT NULL,
    TransactionId INT NOT NULL,
    
    CONSTRAINT FK_CONSUMABLES_WAREHOUSESTOCK FOREIGN KEY(ConsumableId) REFERENCES Consumables(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
	CONSTRAINT FK_WAREHOUSES_WAREHOUSESTOCK FOREIGN KEY(WarehouseId) REFERENCES Warehouses(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
    CONSTRAINT FK_TRANSACTIONS_WAREHOUSESTOCK FOREIGN KEY(TransactionId) REFERENCES Transactions(Id)
    ON DELETE NO ACTION
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS Utilizations(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    Quantity INT NOT NULL,
    WarehouseStockId INT NOT NULL,
    AppointmentId INT NULL,
    DateOfUse DATE NOT NULL,
    WorkerId INT NOT NULL,
    
    CONSTRAINT FK_WAREHOUSESTOCK_UTILIZATIONS FOREIGN KEY(WarehouseStockId) REFERENCES WarehouseStock(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
	CONSTRAINT FK_APPOINTMENTS_UTILIZATIONS FOREIGN KEY(AppointmentId) REFERENCES Appointments(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
	CONSTRAINT FK_WORKERS_MEDICALVACATIONS FOREIGN KEY(WorkerId) REFERENCES Workers(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS MedicalDevices(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    DeviceName VARCHAR(50) NOT NULL,
    Producer VARCHAR(20) NOT NULL,
    ServicePhoneNumber VARCHAR(13) NOT NULL,
    LicenseExpiration VARCHAR(30) NOT NULL,
    DeviceStatus ENUM('Працює', 'Зламано', 'Обслуговується') NOT NULL,
    SerialNumber VARCHAR(25) NOT NULL,
    LicenseExpiration DATE NOT NULL,
    WarehouseId INT NOT NULL,
    
    CONSTRAINT UQ_DEVICES_SERIALNUMBER UNIQUE(SerialNumber),
    
    CONSTRAINT FK_WAREHOUSE_MEDICALDEVICES FOREIGN KEY(WarehouseId) REFERENCES Warehouses(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS AppointmentsMedicalDevices(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    AppointmentId INT NOT NULL,
    DeviceId INT NOT NULL,
    
    CONSTRAINT FK_APPOINTMENTS_APPOINTMENTSMEDICALDEVICES FOREIGN KEY(AppointmentId) REFERENCES Appointments(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
    CONSTRAINT FK_MEDICALDEVICES_APPOINTMENTSMEDICALDEVICES FOREIGN KEY(DeviceId) REFERENCES MedicalDevices(Id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS DeviceMaintance(
	Id INT PRIMARY KEY AUTO_INCREMENT,
    DeviceId INT NOT NULL,
    MaintanceDescription VARCHAR(50) NOT NULL,
    ServiceDate DATE NOT NULL,
    MaintanceType ENUM('Огляд', 'Ремонт') NOT NULL,
    TransactionId INT NOT NULL,
    NextMaintanance DATE NULL,
    
    CONSTRAINT C_NEXTMAIN_AFTER_CURRENT CHECK(NextMaintance > ServiceDate),
    
    CONSTRAINT FK_MEDICALDEVICES_DEVICEMAINTANANCE FOREIGN KEY(DeviceId) REFERENCES MedicalDevices(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
    
	CONSTRAINT FK_TRANSACTIONS_DEVICEMAINTANANCE FOREIGN KEY(TransactionId) REFERENCES Transactions(Id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);




